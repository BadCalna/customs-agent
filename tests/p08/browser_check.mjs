/** Optional real-browser acceptance; Playwright is a test tool, not an app dependency. */
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir, writeFile} from 'node:fs/promises';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {resolve, sep} from 'node:path';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.P08_PLAYWRIGHT || 'playwright');
const base = process.env.P08_BASE_URL || 'http://127.0.0.1:8788';
const output = process.env.P08_OUTPUT_DIR ? pathToFileURL(resolve(process.env.P08_OUTPUT_DIR)+sep) : new URL('../../.local/p08/', import.meta.url);
await mkdir(output, {recursive:true});
const browser = await chromium.launch({headless:true, ...(process.env.P08_BROWSER ? {executablePath:process.env.P08_BROWSER}:{channel:'chrome'})});
const page = await browser.newPage({viewport:{width:1480,height:1100}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const checks=[];
try {
  await page.goto(base+'/p08/');
  await page.getByText('技术失败 1 项',{exact:true}).waitFor();
  assert.equal(await page.locator('.p08-task').count(),1);checks.push('初始分页及服务端8项/1失败');
  assert.equal(await page.locator('.p08-run-row').count(),8);
  await page.getByRole('button',{name:'选择可重试失败行'}).click();
  assert.equal(await page.locator('[data-failed]:checked').count(),1);
  await page.getByRole('button',{name:'重试所选 1 项'}).click();
  await page.getByText('该功能尚未接通',{exact:true}).waitFor();
  assert.equal(await page.locator('[data-failed]:checked').count(),1);checks.push('501不伪造成功并保留失败行');
  await page.getByLabel('演练场景').selectOption('conflict');
  await page.getByRole('button',{name:'选择可重试失败行'}).click();
  await page.getByRole('button',{name:'重试所选 1 项'}).click();
  await page.getByText('内容已更新，请刷新',{exact:true}).waitFor();checks.push('409冲突提示');
  await page.getByLabel('演练场景').selectOption('network');
  await page.getByText('暂时无法更新',{exact:true}).waitFor();
  await page.getByRole('button',{name:'重新连接'}).click();
  await page.getByText('连接暂时不可用，请点击重新连接',{exact:true}).waitFor();checks.push('断线与手动重连');
  await page.getByLabel('演练场景').selectOption('running');
  await page.getByText('0 / 8 项已结束',{exact:false}).waitFor();
  const first = await page.locator('.p08-progress-label').innerText();
  await page.waitForTimeout(2800);
  assert.equal(await page.locator('.p08-progress-label').innerText(),first);checks.push('轮询不按时间伪造进度');
  await page.getByLabel('演练场景').selectOption('normal');
  const options=await page.locator('#version option').evaluateAll(nodes=>nodes.map(n=>({value:n.value,text:n.textContent})));
  await page.getByLabel('文件版本').selectOption(options.find(o=>o.text.includes('V1')).value);
  await page.getByText('历史执行 · 只读',{exact:true}).waitFor();checks.push('V1历史只读');
  await page.getByLabel('文件版本').selectOption(options.find(o=>o.text.includes('V2')).value);
  await page.getByText('技术失败 1 项',{exact:true}).waitFor();
  await page.getByRole('button',{name:'下一页',exact:true}).click();
  await page.getByRole('button',{name:/契约演示-专家改码/}).waitFor();
  await page.getByRole('button',{name:/契约演示-专家改码/}).click();
  await page.getByRole('heading',{name:'专家AI核查',exact:true}).waitFor();checks.push('翻页与专家阶段分离');
  await page.getByText('有核查问题，待专家确认',{exact:true}).waitFor();
  assert.equal(await page.locator('.p08-business-summary').innerText(),'已返回的成功行中，1 项有已返回的核查问题。核查问题不计入技术失败。');
  assert.doesNotMatch(await page.locator('#progress').innerText(),/未知状态：未提供|编码一致|编码不一致|原码缺失/);
  await page.locator('.p08-row-link').first().click();
  assert.match(await page.locator('#selection').innerText(),/已选择版本.*的商品/);
  await page.screenshot({path:fileURLToPath(new URL('expert-issues.png',output)),fullPage:true});
  checks.push('专家核查仅显示已返回问题，空比较状态不报未知错误');
  await page.getByLabel('演练场景').selectOption('expert-no-issues');
  await page.getByText('核查执行已完成，详细结论请查看商品详情',{exact:true}).waitFor();
  assert.equal(await page.locator('.p08-business-summary').count(),0);
  assert.match(await page.locator('#progress').innerText(),/未返回问题不代表核查通过/);
  assert.doesNotMatch(await page.locator('#progress').innerText(),/未知状态：未提供|编码一致|编码不一致|原码缺失/);
  await page.screenshot({path:fileURLToPath(new URL('expert-no-issues.png',output)),fullPage:true});
  checks.push('专家无问题列表不增加待核计数，不推断审核通过');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
  await page.screenshot({path:fileURLToPath(new URL('expert-mobile.png',output)),fullPage:true});
  checks.push('专家核查390px布局');
  await page.setViewportSize({width:1480,height:1100});
  await page.getByLabel('演练场景').selectOption('normal');
  await page.getByRole('button',{name:'上一页',exact:true}).click();
  await page.getByRole('button',{name:/契约演示-主流程/}).click();
  await page.getByText('技术失败 1 项',{exact:true}).waitFor();
  await page.screenshot({path:fileURLToPath(new URL('desktop.png',output)),fullPage:true});
  await page.getByLabel('业务阶段').selectOption('uploaded');
  await page.getByText('该阶段暂无任务',{exact:true}).waitFor();checks.push('阶段空状态');
  await page.getByLabel('业务阶段').selectOption('');
  await page.setViewportSize({width:390,height:844});
  const fits=await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth);
  assert.equal(fits,true,'窄屏不应横向溢出');
  await page.screenshot({path:fileURLToPath(new URL('mobile.png',output)),fullPage:true});
  checks.push('390px窄屏布局');
  assert.deepEqual(errors,[]);checks.push('无浏览器脚本错误');
  await writeFile(new URL('browser-results.json',output),JSON.stringify({checks,errors,browser:browser.version()},null,2));
  process.stdout.write(JSON.stringify({checks,errors,browser:browser.version()},null,2));
} finally { await browser.close(); }
