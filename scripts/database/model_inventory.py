"""One inventory for P12 export, import guards and verification.

Content types and permissions are generated by migrate. Natural foreign keys
resolve references to them in the target database instead of reusing their IDs.
Every other managed model, including future app models, is retained.
"""
from django.apps import apps

GENERATED_MODELS = {"contenttypes.contenttype", "auth.permission"}


def migration_models():
    models = [model for model in apps.get_models()
              if model._meta.managed and not model._meta.proxy
              and model._meta.label_lower not in GENERATED_MODELS]
    # Natural references to groups/users must be available when deserializing.
    first = {"auth.group": 0, "accounts.user": 1}
    return sorted(models, key=lambda model: (first.get(model._meta.label_lower, 2), model._meta.label_lower))


def verification_models():
    models = list(migration_models())
    for model in migration_models():
        for field in model._meta.local_many_to_many:
            through = field.remote_field.through
            if through._meta.auto_created and through not in models:
                models.append(through)
    return models


def validate_source_history(source):
    """Refuse a source from an unmerged branch before migrate can discard columns."""
    from django.db import connection
    from django.db.migrations.loader import MigrationLoader

    known = MigrationLoader(connection, load=True).disk_migrations
    installed = {config.label for config in apps.get_app_configs()}
    applied = source.execute("SELECT app, name FROM django_migrations").fetchall()
    unknown = [(app, name) for app, name in applied if app in installed and (app, name) not in known]
    if unknown:
        raise ValueError(f"源库包含当前代码未知迁移，先集成对应分支再迁移，禁止忽略字段：{unknown}")


def validate_source_schema(source):
    """No populated table or column may silently fall outside the copy inventory."""
    models = verification_models()
    expected = {model._meta.db_table: {field.column for field in model._meta.concrete_fields}
                for model in models}
    ignored = {"django_migrations", "django_content_type", "auth_permission", "sqlite_sequence"}
    for (table,) in source.execute("SELECT name FROM sqlite_master WHERE type='table'"):
        quoted = '"' + table.replace('"', '""') + '"'
        if table in ignored or not source.execute(f"SELECT 1 FROM {quoted} LIMIT 1").fetchone():
            continue
        if table not in expected:
            raise ValueError(f"源库非空表不在迁移清单：{table}")
        extra = {row[1] for row in source.execute(f"PRAGMA table_info({quoted})")} - expected[table]
        if extra:
            raise ValueError(f"源库字段在当前模型中不存在，拒绝丢弃：{table}: {sorted(extra)}")


def validate_generated_metadata(source):
    """Only metadata reproducible by migrate may be excluded from the fixture.

    Custom/stale permissions and content types must fail closed, including ones
    currently unreferenced by users/groups. Never silently discard those rows.
    """
    from django.contrib.auth.management import _get_all_permissions
    from django.utils import translation

    expected_types, expected_permissions = set(), set()
    with translation.override(None):
        for model in apps.get_models():
            opts = model._meta
            key = (opts.app_label, opts.model_name)
            expected_types.add(key)
            expected_permissions.update((*key, code, str(name)) for code, name in _get_all_permissions(opts))
    source_types = set(source.execute('SELECT app_label, model FROM django_content_type'))
    source_permissions = set(source.execute(
        'SELECT c.app_label,c.model,p.codename,p.name FROM auth_permission p '
        'LEFT JOIN django_content_type c ON c.id=p.content_type_id'))
    if source_types - expected_types or source_permissions - expected_permissions:
        raise ValueError("源库存在不能由当前 migrate 重建的自定义/旧元数据，拒绝丢弃："
                         f"contenttypes={source_types - expected_types}; permissions={source_permissions - expected_permissions}")


